#!/usr/bin/env node
// Builds ipa_synth/index_data.js: Word Map concepts (id + en/ja label) and language names (en/ja)
// so the synth page can offer every cell without loading the whole Word Map.
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const ctx = { WORDS: {} }; vm.createContext(ctx);
const concepts = [];
const codes = new Set();
for (const f of fs.readdirSync(path.join(ROOT, 'words')).filter(f => f.endsWith('.js')).sort()) {
    vm.runInContext(fs.readFileSync(path.join(ROOT, 'words', f), 'utf8'), ctx);
    const id = f.slice(0, -3), w = ctx.WORDS[id];
    if (!w || !w.data) continue;
    concepts.push([id, (w.label && w.label.en) || id, (w.label && w.label.ja) || '']);
    for (const c of Object.keys(w.data)) codes.add(c);
}
vm.runInContext(fs.readFileSync(path.join(ROOT, 'lang_names.js'), 'utf8') + ';this.LN=LANG_NAMES;', ctx);
const names = {};
for (const c of [...codes].sort()) names[c] = [(ctx.LN.en && ctx.LN.en[c]) || c, (ctx.LN.ja && ctx.LN.ja[c]) || ''];
const out = '/* GENERATED by ipa_synth/build_index.js */\nwindow.IPA_SYNTH_INDEX = ' + JSON.stringify({ concepts, names }) + ';\n';
fs.writeFileSync(path.join(__dirname, 'index_data.js'), out);
console.log('concepts', concepts.length, 'codes', codes.size, 'bytes', out.length);
