#!/usr/bin/env python3
"""
build_cjk_page_subsets.py — one small woff2 per CJK font and weight for the
Name Map and Time Map.

Google Fonts serves Noto Sans/Serif JP, SC and KR as ~100 unicode-range
slices each. With six families at two weights the page carried over a
thousand @font-face rules, and every layout paid for matching against them:
3.4 s for one forced layout on a 4x-throttled phone (rally r22). These pages
show a fixed set of CJK characters (names, calendars, their UI strings), so
each face is fetched from Google with &text= (Google's own subsetter) in
chunks of CHUNK characters (longer text lists come back as the full slice set,
or as HTTP 400), saved under fonts/, and the page declares those few faces
itself, each with the unicode-range of its chunk.

Run after the names, calendars or their translations change:
    python3 tools/build_cjk_page_subsets.py
It rewrites fonts/cjk-<page>-*.woff2 and the CSS block between the
CJK-SUBSET markers in namemap.html / timemap.html. Each face's unicode-range is
the chunk cut down to the glyphs Google actually returned (a JP chunk does not
hold Hangul; claiming it fetched files the page never used, r24), and each
url() carries ?v=<content hash>, since fonts/ is served immutable (r24). --check reports whether
the pages' characters are all covered (for tools/check_all.js).
"""
import glob, hashlib, os, re, sys, urllib.parse, urllib.request
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124 Safari/537.36 LangMap-build (https://langmaps.com)'
CJK = re.compile('[　-〿぀-ヿ㄀-ㄯ㄰-㆏ㇰ-ㇿ㐀-䶿一-鿿'
                 '가-힯豈-﫿＀-￯]')
PAGES = {
    'namemap': {
        'html': 'namemap.html',
        'sources': ['namemap.html', 'namemap_data.js', 'namemap_i18n.js', 'namemap_names_ext.js',
                    'namemap_content_i18n.js', 'namemap_i18n/*.js', 'nav-short.js',
                    'share-button.js', 'pwa.js', 'lang-picker.js'],   # shared scripts these pages load (r23)
        'faces': [('Noto Sans JP', (400, 700)), ('Noto Sans SC', (400, 700)), ('Noto Sans KR', (400, 700)),
                  ('Noto Serif JP', (700,)), ('Noto Serif SC', (700,)), ('Noto Serif KR', (700,))],
    },
    'timemap': {
        'html': 'timemap.html',
        'sources': ['timemap.html', 'timemap_calendars.js', 'timemap_i18n/*.js', 'nav-short.js',
                    'share-button.js', 'pwa.js', 'lang-picker.js'],
        # Sans on the map labels (owner 2026-10-21: 「地図上のフォントはsans serifに統一」);
        # serif 700 only for the 字 nav icon, as on the Name Map.
        'faces': [('Noto Sans JP', (400, 700)), ('Noto Sans SC', (400, 700)), ('Noto Sans KR', (400, 700)),
                  ('Noto Serif JP', (700,)), ('Noto Serif SC', (700,)), ('Noto Serif KR', (700,))],
    },
}
START, END = '/* CJK-SUBSET:START', '/* CJK-SUBSET:END */'
CHUNK = 600


def chars_of(page):
    s = set()
    for pat in PAGES[page]['sources']:
        for f in sorted(glob.glob(os.path.join(ROOT, pat))):
            s.update(CJK.findall(open(f, encoding='utf-8').read()))
    return ''.join(sorted(s))


def fetch_face(family, weight, text):
    q = urllib.parse.urlencode({'family': f'{family}:wght@{weight}', 'text': text, 'display': 'swap'})
    req = urllib.request.Request('https://fonts.googleapis.com/css2?' + q, headers={'User-Agent': UA})
    css = urllib.request.urlopen(req, timeout=60).read().decode()
    urls = re.findall(r'url\((https://[^)]+)\)', css)
    if len(urls) != 1:
        raise SystemExit(f'{family} {weight}: expected one file, got {len(urls)}')
    return urllib.request.urlopen(urllib.request.Request(urls[0], headers={'User-Agent': UA}), timeout=60).read()


def chunks(text):
    return [text[i:i + CHUNK] for i in range(0, len(text), CHUNK)]


def urange(chars):
    cps = sorted(ord(c) for c in chars)
    out, a = [], cps[0]
    for prev, cur in zip(cps, cps[1:] + [None]):
        if cur != prev + 1:
            out.append(f'U+{a:X}' if a == prev else f'U+{a:X}-{prev:X}')
            a = cur
    return ', '.join(out)


def fname(page, fam, w, i):
    return f"fonts/cjk-{page}-{fam.lower().replace(' ', '')}-{w}-{i}.woff2"


def covered(path, chunk):
    """The chunk's characters that the saved file really has, and its hash."""
    try:
        data = open(path, 'rb').read()
        cmap = TTFont(path).getBestCmap()
    except OSError:
        return chunk, 'missing'
    return ''.join(c for c in chunk if ord(c) in cmap), hashlib.sha256(data).hexdigest()[:10]


def block(page, text):
    lines = [START + ' — generated by tools/build_cjk_page_subsets.py; do not edit by hand.',
             f'   {len(text)} characters. */']
    for fam, weights in PAGES[page]['faces']:
        for w in weights:
            for i, ch in enumerate(chunks(text)):
                fn = fname(page, fam, w, i)
                have, h = covered(os.path.join(ROOT, fn), ch)
                if not have:
                    continue
                lines.append(f"@font-face {{ font-family: '{fam}'; font-style: normal; font-weight: {w}; font-display: swap; "
                             f"src: url('{fn}?v={h}') format('woff2'); unicode-range: {urange(have)}; }}")
    lines.append(END)
    return '\n'.join(lines)


def main():
    check = '--check' in sys.argv
    stale = 0
    for page, cfg in PAGES.items():
        text = chars_of(page)
        html_path = os.path.join(ROOT, cfg['html'])
        html = open(html_path, encoding='utf-8').read()
        m = re.search(re.escape(START) + r'.*?' + re.escape(END), html, re.S)
        want = block(page, text)
        if check:
            ok = m and m.group(0) == want
            print(f"{page}: {'up to date' if ok else 'STALE'} ({len(text)} chars)")
            stale += 0 if ok else 1
            continue
        for old in glob.glob(os.path.join(ROOT, 'fonts', f'cjk-{page}-*.woff2')):
            os.remove(old)
        for fam, weights in cfg['faces']:
            for w in weights:
                for i, ch in enumerate(chunks(text)):
                    data = fetch_face(fam, w, ch)
                    fn = os.path.join(ROOT, fname(page, fam, w, i))
                    open(fn, 'wb').write(data)
                    print(f'  {os.path.basename(fn)}: {len(data) // 1024} KB')
        if not m:
            raise SystemExit(f'{cfg["html"]}: add the {START} … {END} markers inside a <style> first')
        html = html[:m.start()] + block(page, text) + html[m.end():]   # after the fetch: ranges and hashes come from the new files
        open(html_path, 'w', encoding='utf-8').write(html)
        print(f'{page}: {len(text)} characters')
    if check:
        print(f'stale: {stale}')
        sys.exit(1 if stale else 0)


if __name__ == '__main__':
    main()
