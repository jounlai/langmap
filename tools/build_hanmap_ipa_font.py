#!/usr/bin/env python3
"""
build_hanmap_ipa_font.py — a self-hosted Gentium Plus subset ('Han Map IPA')
holding exactly the Latin / IPA / combining characters the Han Map's readings
use, listed first in the label and cell font stacks.

Google's Gentium Plus and Noto Serif slices do not hold a base letter and a
combining mark such as U+031A (p̚ t̚ k̚, Cantonese/Hakka finals) or U+030D (ŋ̍,
Min) as one cluster, so Chrome walked the whole label font list for a font
that did: ~20 extra Latin files of rare-script families (Mongolian, Tibetan,
Coptic …), each one re-laying out the map — 27 font relayouts and ~300 KB on
every load (rally r22). With every character of the readings in the first
font, the cluster resolves there.

Run after hanmap_data.js gains characters:  python3 tools/build_hanmap_ipa_font.py
--check reports whether the face still covers the data (tools/check_all.js).
"""
import os, re, sys, urllib.parse, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124 Safari/537.36 LangMap-build (https://langmaps.com)'
START, END = '/* HANMAP-IPA:START', '/* HANMAP-IPA:END */'
WEIGHTS = (400, 700)


def wanted(c):
    o = ord(c)
    return (0x20 < o < 0x370) or (0x1D00 <= o <= 0x1DFF) or (0x2070 <= o <= 0x209F) or (0xA700 <= o <= 0xA71F) \
        or o in (0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026)


def chars():
    s = open(os.path.join(ROOT, 'hanmap_data.js'), encoding='utf-8').read()
    return ''.join(sorted(set(c for c in s if wanted(c))))


def urange(text):
    cps = sorted(ord(c) for c in text)
    out, a = [], cps[0]
    for prev, cur in zip(cps, cps[1:] + [None]):
        if cur != prev + 1:
            out.append(f'U+{a:X}' if a == prev else f'U+{a:X}-{prev:X}')
            a = cur
    return ', '.join(out)


def block(text):
    lines = [START + ' — generated by tools/build_hanmap_ipa_font.py; do not edit by hand.', f'   {len(text)} characters. */']
    for w in WEIGHTS:
        lines.append(f"@font-face {{ font-family: 'Han Map IPA'; font-style: normal; font-weight: {w}; font-display: swap; "
                     f"src: url('fonts/hanmap-ipa-{w}.woff2') format('woff2'); unicode-range: {urange(text)}; }}")
    lines.append(END)
    return '\n'.join(lines)


def main():
    text = chars()
    p = os.path.join(ROOT, 'hanmap.html')
    html = open(p, encoding='utf-8').read()
    m = re.search(re.escape(START) + r'.*?' + re.escape(END), html, re.S)
    want = block(text)
    if '--check' in sys.argv:
        ok = bool(m and m.group(0) == want)
        print(f"hanmap ipa: {'up to date' if ok else 'STALE'} ({len(text)} chars)\nstale: {0 if ok else 1}")
        sys.exit(0 if ok else 1)
    if not m:
        raise SystemExit(f'hanmap.html: add the {START} … {END} markers inside a <style> first')
    for w in WEIGHTS:
        q = urllib.parse.urlencode({'family': f'Gentium Plus:wght@{w}', 'text': text, 'display': 'swap'})
        css = urllib.request.urlopen(urllib.request.Request('https://fonts.googleapis.com/css2?' + q, headers={'User-Agent': UA}), timeout=60).read().decode()
        urls = re.findall(r'url\((https://[^)]+)\)', css)
        if len(urls) != 1:
            raise SystemExit(f'weight {w}: expected one file, got {len(urls)}')
        data = urllib.request.urlopen(urllib.request.Request(urls[0], headers={'User-Agent': UA}), timeout=60).read()
        open(os.path.join(ROOT, 'fonts', f'hanmap-ipa-{w}.woff2'), 'wb').write(data)
        print(f'  hanmap-ipa-{w}.woff2: {len(data) // 1024} KB')
    open(p, 'w', encoding='utf-8').write(html[:m.start()] + want + html[m.end():])
    print(f'hanmap ipa: {len(text)} characters')


if __name__ == '__main__':
    main()
