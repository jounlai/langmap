#!/usr/bin/env node
/*
 * build_hanmap_trivia_rt.js — split hanmap_trivia.js into what a reader
 * actually downloads.
 *
 * hanmap_trivia.js carries every article body in all 19 UI languages inline:
 * 4.5 MB raw, 1.4 MB over the wire, fetched by every Han Map visitor at idle
 * although each reader only ever reads one language (Lighthouse, 2026-10-16).
 * The source stays the single file the trivia guards and the SEO export read;
 * this tool writes the runtime copy the page loads:
 *
 *   hanmap_trivia_rt/base.js   every field of every article, titles and
 *                              summaries in all languages, bodies in en only
 *                              (the fallback while another language loads)
 *   hanmap_trivia_rt/<ui>.js   the bodies in one other language, as
 *                              window.HANMAP_TRIVIA_BODY[ui][id] = html
 *
 * base.js carries a hash of the whole source, so any body edit changes it and
 * its ?v= — and the per-language files are requested with that same ?v=.
 *
 *   node tools/build_hanmap_trivia_rt.js           # write
 *   node tools/build_hanmap_trivia_rt.js --check   # print "stale: N" (check_all)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'hanmap_trivia.js');
const OUT = path.join(ROOT, 'hanmap_trivia_rt');
const INLINE = new Set(['en']);

function build() {
    const text = fs.readFileSync(SRC, 'utf8');
    const ctx = vm.createContext({});
    vm.runInContext('var window = this;', ctx);
    vm.runInContext(text, ctx, { filename: 'hanmap_trivia.js' });
    const arts = JSON.parse(JSON.stringify(vm.runInContext('window.TRIVIA_ARTICLES', ctx) || []));
    const hash = crypto.createHash('sha1').update(text).digest('hex').slice(0, 12);
    const per = {};
    for (const a of arts) {
        const body = a.body || {};
        const keep = {};
        for (const ui of Object.keys(body)) {
            if (INLINE.has(ui)) { keep[ui] = body[ui]; continue; }
            (per[ui] = per[ui] || {})[a.id] = body[ui];
        }
        a.body = keep;
    }
    const files = {};
    files['base.js'] = '// GENERATED by tools/build_hanmap_trivia_rt.js from hanmap_trivia.js — do not edit.\n'
        + 'window.HANMAP_TRIVIA_BUILD = ' + JSON.stringify(hash) + ';\n'
        + 'window.TRIVIA_ARTICLES = ' + JSON.stringify(arts) + ';\n';
    for (const ui of Object.keys(per).sort()) {
        files[ui + '.js'] = '// GENERATED by tools/build_hanmap_trivia_rt.js from hanmap_trivia.js — do not edit.\n'
            + '(window.HANMAP_TRIVIA_BODY = window.HANMAP_TRIVIA_BODY || {})[' + JSON.stringify(ui) + '] = '
            + JSON.stringify(per[ui]) + ';\n';
    }
    return files;
}

const files = build();
if (process.argv.includes('--check')) {
    const stale = [];
    for (const [f, s] of Object.entries(files)) {
        const p = path.join(OUT, f);
        if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== s) stale.push(f);
    }
    const extra = fs.existsSync(OUT) ? fs.readdirSync(OUT).filter((f) => !(f in files)) : [];
    if (stale.length || extra.length) {
        console.log('hanmap_trivia_rt/ is stale: ' + stale.concat(extra.map((f) => f + ' (orphan)')).join(', '));
        console.log('fix: node tools/build_hanmap_trivia_rt.js && node tools/page_asset_version_check.js --bump');
    }
    console.log('stale: ' + (stale.length + extra.length));
} else {
    fs.mkdirSync(OUT, { recursive: true });
    for (const f of fs.readdirSync(OUT)) if (!(f in files)) fs.unlinkSync(path.join(OUT, f));
    for (const [f, s] of Object.entries(files)) fs.writeFileSync(path.join(OUT, f), s);
    console.log('wrote ' + Object.keys(files).length + ' files to hanmap_trivia_rt/');
}
