#!/usr/bin/env python3
"""
build_ipa_fonts.py — a self-hosted Gentium Plus subset per map ('Han Map IPA',
'Word Map IPA') holding exactly the Latin / IPA / combining characters that
map's readings use, listed first in its label font stacks.

Google's Gentium Plus and Noto Serif slices do not hold a base letter and a
combining mark such as U+031A (p̚ t̚ k̚), U+030D (ŋ̍), U+032F (ɪ̯) or U+0325
(ɯ̥) as one cluster, so Chrome walked the whole label font list for a font that
did: ~20-70 extra Latin files of rare-script families, each one re-laying out
the map (Han Map r22: 27 relayouts, ~300 KB; Word Map r24: 84 files, 60
relayouts on a phone). With every character of the readings in the first font,
the cluster resolves there.

The url() carries ?v=<content hash>: production serves fonts/ immutable for a
year, and these files are rewritten under the same names (r24).

Run after the data gains characters:  python3 tools/build_ipa_fonts.py
--check reports whether each face still covers its data (tools/check_all.js).
"""
import glob, hashlib, os, re, sys, urllib.parse, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124 Safari/537.36 LangMap-build (https://langmaps.com)'
WEIGHTS = (400, 700)
PAGES = {
    'hanmap': {'html': 'hanmap.html', 'family': 'Han Map IPA', 'file': 'hanmap-ipa', 'marker': 'HANMAP-IPA',
               'sources': ['hanmap_data.js']},
    'wordmap': {'html': 'wordmap.html', 'family': 'Word Map IPA', 'file': 'wordmap-ipa', 'marker': 'WORDMAP-IPA',
                'sources': ['wordmap_data.js', 'word_labels.js', 'words/*.js']},
}


def wanted(c):
    o = ord(c)
    return (0x20 < o < 0x370) or (0x1D00 <= o <= 0x1EFF) or (0x2070 <= o <= 0x209F) or (0x2C60 <= o <= 0x2C7F) or (0xA700 <= o <= 0xA7FF) \
        or o in (0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026)


def chars(cfg):
    s = set()
    for pat in cfg['sources']:
        for f in sorted(glob.glob(os.path.join(ROOT, pat))):
            s.update(c for c in open(f, encoding='utf-8').read() if wanted(c))
    return ''.join(sorted(s))


def urange(text):
    cps = sorted(ord(c) for c in text)
    out, a = [], cps[0]
    for prev, cur in zip(cps, cps[1:] + [None]):
        if cur != prev + 1:
            out.append(f'U+{a:X}' if a == prev else f'U+{a:X}-{prev:X}')
            a = cur
    return ', '.join(out)


def fhash(path):
    try:
        return hashlib.sha256(open(path, 'rb').read()).hexdigest()[:10]
    except OSError:
        return 'missing'


def block(cfg, text):
    start = f"/* {cfg['marker']}:START"
    lines = [start + ' — generated by tools/build_ipa_fonts.py; do not edit by hand.', f'   {len(text)} characters. */']
    for w in WEIGHTS:
        fn = f"fonts/{cfg['file']}-{w}.woff2"
        lines.append(f"@font-face {{ font-family: '{cfg['family']}'; font-style: normal; font-weight: {w}; font-display: swap; "
                     f"src: url('{fn}?v={fhash(os.path.join(ROOT, fn))}') format('woff2'); unicode-range: {urange(text)}; }}")
    lines.append(f"/* {cfg['marker']}:END */")
    return '\n'.join(lines)


def main():
    check = '--check' in sys.argv
    stale = 0
    for page, cfg in PAGES.items():
        text = chars(cfg)
        p = os.path.join(ROOT, cfg['html'])
        html = open(p, encoding='utf-8').read()
        start, end = f"/* {cfg['marker']}:START", f"/* {cfg['marker']}:END */"
        m = re.search(re.escape(start) + r'.*?' + re.escape(end), html, re.S)
        # Covered = the block's range equals the data's characters (the hash
        # only changes when the files are rebuilt).
        if check:
            ok = bool(m and f'unicode-range: {urange(text)};' in m.group(0) and m.group(0) == block(cfg, text))
            print(f"{page} ipa: {'up to date' if ok else 'STALE'} ({len(text)} chars)")
            stale += 0 if ok else 1
            continue
        if not m:
            raise SystemExit(f'{cfg["html"]}: add the {start} … {end} markers inside a <style> first')
        for w in WEIGHTS:
            q = urllib.parse.urlencode({'family': f'Gentium Plus:wght@{w}', 'text': text, 'display': 'swap'})
            css = urllib.request.urlopen(urllib.request.Request('https://fonts.googleapis.com/css2?' + q, headers={'User-Agent': UA}), timeout=60).read().decode()
            urls = re.findall(r'url\((https://[^)]+)\)', css)
            if len(urls) != 1:
                raise SystemExit(f'{page} weight {w}: expected one file, got {len(urls)}')
            data = urllib.request.urlopen(urllib.request.Request(urls[0], headers={'User-Agent': UA}), timeout=60).read()
            open(os.path.join(ROOT, 'fonts', f"{cfg['file']}-{w}.woff2"), 'wb').write(data)
            print(f"  {cfg['file']}-{w}.woff2: {len(data) // 1024} KB")
        open(p, 'w', encoding='utf-8').write(html[:m.start()] + block(cfg, text) + html[m.end():])
        print(f'{page} ipa: {len(text)} characters')
    if check:
        print(f'stale: {stale}')
        sys.exit(1 if stale else 0)


if __name__ == '__main__':
    main()
