#!/usr/bin/env node
/*
 * build_lang_words.js — split words/<id>.js into one file per LANGUAGE.
 *
 * The word files are organised by concept: words/water.js holds water for all
 * 1,164 languages. That is the right shape for the map, which draws one concept
 * across every language at a time, and wordmap.html loads exactly one of them
 * on first paint.
 *
 * The language modal wants the transpose — every concept for ONE language — and
 * the only way to get it used to be to download all ~55 word files, 2.1 MB, to
 * read 55 cells out of them. That defeated the whole staged loader: the first
 * click on any language pulled the entire corpus.
 *
 * So this writes the transpose out ahead of time. Each file is a single call:
 *     window.__wmLangWordsAdd('zh', { water: ['水','ʂwei˨˩˦'], … }, { … alt … });
 * ~1.8 KB per language instead of 2.1 MB, and the receiver in wordmap.html
 * merges it into LANG_DATA[code].words exactly the way _mergeWordsIntoLangData
 * does, so every consumer downstream is unchanged.
 *
 * The third argument carries `alt` script variants (Sawndip, Khitan, Jurchen —
 * the object-form cells) and is omitted when a language has none.
 *
 * Run: node tools/build_lang_words.js           (writes lang_words/)
 *      node tools/build_lang_words.js --check   (prints "stale: N")
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const OUTDIR = path.join(ROOT, 'lang_words');
const CHECK = process.argv.includes('--check');

// LANG_DATA decides which codes get a file; WORD_ORDER decides the key order,
// so a rebuild after adding a word produces a minimal diff.
const LANG_DATA = (() => {
    const ctx = vm.createContext({ window: {} });
    vm.runInContext(fs.readFileSync(path.join(ROOT, 'wordmap_data.js'), 'utf8')
        .replace(/^const /gm, 'var '), ctx);
    return vm.runInContext('LANG_DATA', ctx);
})();
const WORD_ORDER = (() => {
    const ctx = vm.createContext({ window: {} });
    vm.runInContext(fs.readFileSync(path.join(ROOT, 'word_manifest.js'), 'utf8')
        .replace(/^const /gm, 'var '), ctx);
    return vm.runInContext('WORD_ORDER', ctx);
})();

const WORDS = (() => {
    const ctx = vm.createContext({});
    vm.runInContext('this.window = this; this.WORDS = window.WORDS = {};', ctx);
    for (const id of WORD_ORDER) {
        const p = path.join(ROOT, 'words', id + '.js');
        if (fs.existsSync(p)) vm.runInContext(fs.readFileSync(p, 'utf8'), ctx, { filename: id + '.js' });
    }
    return ctx.WORDS;
})();

// Transpose: code -> { wordId: [surface, ipa] }, plus code -> { wordId: alt[] }.
const byLang = Object.create(null);
const altByLang = Object.create(null);
for (const id of WORD_ORDER) {
    const w = WORDS[id];
    if (!w || !w.data) continue;
    for (const [code, entry] of Object.entries(w.data)) {
        if (!LANG_DATA[code]) continue;
        const cell = byLang[code] || (byLang[code] = {});
        if (Array.isArray(entry)) {
            cell[id] = entry;
        } else {
            cell[id] = [entry.form || '', entry.ipa || ''];
            if (entry.alt && entry.alt.length) (altByLang[code] || (altByLang[code] = {}))[id] = entry.alt;
        }
    }
}

if (!CHECK) fs.mkdirSync(OUTDIR, { recursive: true });

let stale = 0, written = 0;
const expected = new Set();
for (const code of Object.keys(LANG_DATA)) {
    const cells = byLang[code] || {};
    const alt = altByLang[code];
    const args = [JSON.stringify(code), JSON.stringify(cells)];
    if (alt) args.push(JSON.stringify(alt));
    const body = '/* GENERATED by tools/build_lang_words.js from words/*.js. Do not edit. */\n'
        + `window.__wmLangWordsAdd(${args.join(',')});\n`;
    const file = code + '.js';
    expected.add(file);
    const out = path.join(OUTDIR, file);
    if (CHECK) {
        const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
        if (cur !== body) stale++;
    } else {
        fs.writeFileSync(out, body);
        written++;
    }
}

// A language removed from LANG_DATA must not leave its file behind — the loader
// would keep serving words for a row the map no longer has.
if (fs.existsSync(OUTDIR)) {
    for (const f of fs.readdirSync(OUTDIR).filter(f => f.endsWith('.js'))) {
        if (expected.has(f)) continue;
        if (CHECK) stale++;
        else fs.unlinkSync(path.join(OUTDIR, f));
    }
}

if (CHECK) {
    console.log(`stale: ${stale}`);
    if (stale) console.log('  run: node tools/build_lang_words.js');
    process.exit(0);
}
console.log(`lang_words/ — wrote ${written} file(s) from ${WORD_ORDER.length} word file(s).`);
