#!/usr/bin/env node
/*
 * build_meta_split.js — split the 19 MB wordmap_meta.js so a language popup
 * no longer pulls the whole corpus.
 *
 * wordmap_meta.js is ~19 MB: per-language LANG_DATA[code].meta (11.6 MB, of
 * which .description + .sources are 11.35 MB) PLUS the base META_I18N table.
 * loadMeta() pulled all of it on the first popup (4 min on slow 4G).
 *
 * This emits:
 *   - wordmap_meta_lite.js  : LANG_DATA[code].meta with ONLY the small
 *                             structured fields (family/speakers/script/period/
 *                             …), every language, ~0.27 MB. Loaded by loadMeta()
 *                             for the filter / games / historical view / popup.
 *   - meta_desc/<code>.js   : that one language's .description + .sources
 *                             (~10 KB), Object.assign-merged onto its .meta.
 *                             Loaded only when that language's popup opens.
 *
 * The base META_I18N table stays in wordmap_meta.js for now (Stage 2 splits it
 * per-UI). Run from repo root:  node tools/build_meta_split.js
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const ROOT = path.join(__dirname, '..');

// Fields that are small + needed broadly (map/filter/games/historical). Anything
// NOT here (description, sources) goes to the per-language file.
const LITE_FIELDS = new Set(['family', 'speakers', 'countries', 'official', 'script',
  'scriptTags', 'dataStatus', 'codeType', 'iso6393', 'vitality', 'textDirection',
  'speakerCount', 'parentCode', 'speakerBasis', 'speakerSource', 'speakerYear',
  'glottocode', 'locationBasis', 'pronunciationType', 'surfaceType', 'aliases',
  'reviewStatus', 'coverage', 'baseLang', 'varietyRole', 'languageKind', 'period',
  'disambiguator', 'coverageNote', 'unattestedReason', 'wordsNote', 'extinct',
  'extinctionDate', 'lastSpeaker']);
const DESC_FIELDS = ['description', 'sources']; // the big ones → per-language

const ctx = { window: {}, console };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'wordmap_data.js'), 'utf8') + '\n;this.LANG_DATA=LANG_DATA;', ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'wordmap_meta.js'), 'utf8') +
  '\n;this.META_I18N=(typeof META_I18N!=="undefined")?META_I18N:null;', ctx);
const LD = ctx.LANG_DATA;
const BASE_I18N = ctx.META_I18N; // ~0.35 MB base translation table (was inside wordmap_meta.js)
const codes = Object.keys(LD).filter(c => LD[c] && LD[c].meta);

const q = s => JSON.stringify(s);
// wordmap_meta_lite.js
let lite = '/* wordmap_meta_lite.js — GENERATED by tools/build_meta_split.js.\n' +
  ' * Structured per-language meta only (no description/sources). Drop-in for\n' +
  ' * loadMeta(): sets LANG_DATA[code].meta and fires the same load signal. */\n';
let liteBytes = 0;
const descDir = path.join(ROOT, 'meta_desc');
fs.mkdirSync(descDir, { recursive: true });
let descCount = 0, descBytes = 0;
for (const c of codes) {
  const m = LD[c].meta;
  const small = {}; for (const k of Object.keys(m)) if (LITE_FIELDS.has(k)) small[k] = m[k];
  lite += `(LANG_DATA[${q(c)}]=LANG_DATA[${q(c)}]||{}).meta=Object.assign(LANG_DATA[${q(c)}].meta||{},${JSON.stringify(small)});\n`;
  const big = {}; for (const k of DESC_FIELDS) if (m[k] !== undefined) big[k] = m[k];
  if (Object.keys(big).length) {
    const body = `(LANG_DATA[${q(c)}]=LANG_DATA[${q(c)}]||{}).meta=Object.assign(LANG_DATA[${q(c)}].meta||{},${JSON.stringify(big)});\n`;
    fs.writeFileSync(path.join(descDir, c + '.js'), body);
    descCount++; descBytes += body.length;
  }
}
// The base translation table (translateMetaSmart reads global META_I18N). It
// lived inside wordmap_meta.js; at ~0.35 MB it rides along in the lite file so
// non-English UIs keep their meta translations. Declared exactly as the original
// (top-level const → shared across <script> tags), so meta_i18n_ext.js augments it.
if (BASE_I18N) lite += `const META_I18N = ${JSON.stringify(BASE_I18N)};\n`;
// Same completion signal wordmap_meta.js emits, so loadMeta()'s promise resolves.
lite += 'window._wmMetaLoaded = true;\nif (window._wmMetaResolve) window._wmMetaResolve();\n';
fs.writeFileSync(path.join(ROOT, 'wordmap_meta_lite.js'), lite);
liteBytes = lite.length;
console.error(`wordmap_meta_lite.js: ${(liteBytes / 1024).toFixed(0)} KB (${codes.length} langs)`);
console.error(`meta_desc/: ${descCount} files, ${(descBytes / 1024 / 1024).toFixed(2)} MB total, ${(descBytes / 1024 / descCount).toFixed(1)} KB avg`);
