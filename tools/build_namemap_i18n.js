#!/usr/bin/env node
/*
 * build_namemap_i18n.js — split namemap_content_i18n.js into one file per UI.
 *
 * The source holds four tables keyed by entity, each carrying every UI language
 * at once: country names, language names, each name's meaning, and its
 * background paragraph. namemap.html used to load all 584 KB (217 KB gzipped)
 * of it on every visit and a reader used one nineteenth.
 *
 * Each slice re-does the same merge the source does — Object.assign onto
 * NM_LANGS cells and NAMES[id].origin/background — so it is additive: loading a
 * second UI's slice later, when the reader switches language, adds that UI's
 * strings without disturbing the first.
 *
 * Run: node tools/build_namemap_i18n.js           (writes namemap_i18n/)
 *      node tools/build_namemap_i18n.js --check   (prints "stale: N")
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const OUTDIR = path.join(ROOT, 'namemap_i18n');
const CHECK = process.argv.includes('--check');

const TABLES = (() => {
    const ctx = vm.createContext({});
    vm.runInContext('var window=this; this.window=this; this.NM_LANGS={}; this.NAMES={};'
        + 'this.__NM_I18N_EXPORT=1; this.console={error:function(){}};', ctx);
    vm.runInContext(fs.readFileSync(path.join(ROOT, 'namemap_content_i18n.js'), 'utf8'), ctx);
    return vm.runInContext('__NM_I18N', ctx);
})();

const UIS = (() => {
    const s = new Set();
    for (const t of Object.values(TABLES))
        for (const row of Object.values(t)) for (const ui of Object.keys(row)) s.add(ui);
    return [...s].sort();
})();

// One slice per UI, in the source's own key order so a re-run diffs minimally.
function slice(ui) {
    const out = {};
    for (const [name, table] of Object.entries(TABLES)) {
        const t = {};
        for (const [k, row] of Object.entries(table)) if (ui in row) t[k] = { [ui]: row[ui] };
        out[name] = t;
    }
    return out;
}

const BODY = (ui, t) => `/* GENERATED by tools/build_namemap_i18n.js from namemap_content_i18n.js.
 * NameMap content strings for one UI language. Do not edit. */
(function () {
    'use strict';
    var NM_LANGS = window.NM_LANGS, NAMES = window.NAMES;
    if (!NM_LANGS || !NAMES) { console.error('namemap_i18n/${ui}: data not loaded'); return; }
    var C = ${JSON.stringify(t.COUNTRY_I18N)};
    var L = ${JSON.stringify(t.LANGUAGE_I18N)};
    var M = ${JSON.stringify(t.MEANING_I18N)};
    var B = ${JSON.stringify(t.BACKGROUND_I18N)};
    Object.keys(NM_LANGS).forEach(function (code) {
        var cell = NM_LANGS[code];
        var c = cell.country && C[cell.country.en]; if (c) Object.assign(cell.country, c);
        var l = cell.name && L[cell.name.en]; if (l) Object.assign(cell.name, l);
    });
    Object.keys(NAMES).forEach(function (id) {
        var n = NAMES[id]; if (!n || !n.origin) return;
        var l = n.origin.lang && L[n.origin.lang.en]; if (l) Object.assign(n.origin.lang, l);
        var m = M[id]; if (m && n.origin.meaning) Object.assign(n.origin.meaning, m);
        var b = B[id]; if (b && n.background) Object.assign(n.background, b);
    });
    if (window.__nmI18nLoaded) window.__nmI18nLoaded('${ui}');
})();
`;

if (!CHECK) fs.mkdirSync(OUTDIR, { recursive: true });
let stale = 0, written = 0;
const expected = new Set();
for (const ui of UIS) {
    const body = BODY(ui, slice(ui));
    const file = ui + '.js';
    expected.add(file);
    const out = path.join(OUTDIR, file);
    if (CHECK) {
        const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
        if (cur !== body) stale++;
    } else { fs.writeFileSync(out, body); written++; }
}
if (fs.existsSync(OUTDIR)) {
    for (const f of fs.readdirSync(OUTDIR).filter((f) => f.endsWith('.js'))) {
        if (expected.has(f)) continue;
        if (CHECK) stale++; else fs.unlinkSync(path.join(OUTDIR, f));
    }
}
if (CHECK) {
    console.log(`stale: ${stale}`);
    if (stale) console.log('  run: node tools/build_namemap_i18n.js');
    process.exit(0);
}
console.log(`namemap_i18n/ — wrote ${written} file(s) for ${UIS.length} UI language(s).`);
