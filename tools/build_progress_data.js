#!/usr/bin/env node
/**
 * build_progress_data.js — the per-word coverage table behind progress.html.
 *
 * WHY. 86 words times 1,188 languages is 102,168 cells and roughly a third of
 * them are empty. Deciding what to work on next meant running an ad-hoc node
 * one-liner every time, and the answer "green is at 32%" is not actionable on
 * its own — what makes it actionable is WHICH languages are missing, biggest
 * first, because a gap at Hindi is a different job from a gap at Tangkhul.
 *
 * THE THREE TIERS MATTER MORE THAN THE PERCENTAGE, and the page would lie
 * without them. They come from validate_wordmap_data.js so the two cannot
 * drift:
 *   partial (🧪)  — the concept itself is not universal. cockcrow has no cell
 *                   for a language that does not conventionalise the sound,
 *                   and an empty cell is the correct answer. A low percentage
 *                   here is not a gap.
 *   filling in    — a core word still being filled. Empty IS a gap.
 *   core          — expected everywhere; the validator errors on a hole.
 *
 * FORMAT. The membership matrix ships as a bitmap, one bit per (word,
 * language), base64'd: 102,168 bits is 12.5 KB, where a list of missing codes
 * would be some 300 KB. Everything the page shows — counts, percentages, the
 * missing list for any word, the per-language totals — is computed from it in
 * the browser, so nothing has to be precomputed twice and nothing can
 * disagree with anything else.
 *
 * Bit i*L+j is set when word i is filled for language j, with the word order
 * as WORD_IDS gives it and the language order as data/wordmap_seo.json does.
 *
 *   node tools/build_progress_data.js
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

/** The WIP core words, read from the validator so the two cannot drift. */
function fillingIn() {
    const src = fs.readFileSync(path.join(ROOT, 'validate_wordmap_data.js'), 'utf8');
    const m = src.match(/const FILLING_IN = new Set\(\[([\s\S]*?)\]\)/);
    return new Set([...m[1].matchAll(/'([a-z0-9_]+)'/g)].map((x) => x[1]));
}

/** `partial: true` lives in the word's own file, which is where a reader
 *  looking at the concept would go for it. */
function isPartial(id) {
    const p = path.join(ROOT, 'words', `${id}.js`);
    if (!fs.existsSync(p)) return false;
    const head = fs.readFileSync(p, 'utf8').slice(0, 4000);
    return /\n\s*partial:\s*true/.test(head);
}

function main() {
    const data = JSON.parse(fs.readFileSync(
        path.join(ROOT, 'data/wordmap_seo.json'), 'utf8'));

    const words = data.words.map((w) => w.id);
    const codes = Object.keys(data.langs);
    const filling = fillingIn();

    const W = words.length, L = codes.length;
    const bits = new Uint8Array(Math.ceil(W * L / 8));
    for (let i = 0; i < W; i++) {
        for (let j = 0; j < L; j++) {
            const e = data.langs[codes[j]].words && data.langs[codes[j]].words[words[i]];
            if (!e || !e[0] || e[0] === '—') continue;
            const n = i * L + j;
            bits[n >> 3] |= 1 << (n & 7);
        }
    }

    const out = {
        generated: new Date().toISOString().slice(0, 10),
        langs: codes.map((c) => {
            const l = data.langs[c];
            const m = l.meta || {};
            return [
                c,
                l.name || c,
                m.speakerCount || 0,
                (m.family || '').split('(')[0].trim(),
                m.parentCode ? 1 : 0,          // a variety of another row
                m.period ? 1 : 0,              // historical / ancient
            ];
        }),
        words: words.map((id, i) => [
            id,
            (data.words[i].label && data.words[i].label.en) || id,
            (data.words[i].label && data.words[i].label.ja) || '',
            isPartial(id) ? 'partial' : (filling.has(id) ? 'filling' : 'core'),
        ]),
        bits: Buffer.from(bits).toString('base64'),
    };

    const js = `/* Generated by tools/build_progress_data.js — do not edit.\n`
        + `   ${W} words x ${L} languages as a base64 bitmap; see the tool for the format. */\n`
        + `window.PROGRESS = ${JSON.stringify(out)};\n`;
    fs.writeFileSync(path.join(ROOT, 'progress_data.js'), js);

    let filled = 0;
    for (const b of bits) filled += (b.toString(2).match(/1/g) || []).length;
    console.log(`progress_data.js  ${W} words x ${L} languages`);
    console.log(`  ${filled.toLocaleString()} of ${(W * L).toLocaleString()} cells filled`
        + ` (${(100 * filled / (W * L)).toFixed(1)}%)`);
    console.log(`  ${(js.length / 1024).toFixed(1)} KB`);
}

main();
