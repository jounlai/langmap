FB_ARTIFACTS = [
    (r'👇', 'Facebook teaser line ("👇 Here is the longer story") — the page shows the lead box instead'),
    (r'(?i)here is the longer story', 'Facebook teaser line'),
    (r'langmap\.heuron\.com', 'old domain; use https://langmaps.com'),
    (r'^\s*#\s', 'level-1 heading in the body; the title lives in front matter'),
    (r'\]\((https?://[^)]+)\)\]\(', 'doubled link'),
    (r'^\s*\[(https?://[^\]]+)\]\(\1\)\s*$', 'bare map-link line; put it in map_url/map_label'),
    (r'^\s*🗺', 'Facebook map call-to-action; use map_url/map_label'),
]


_MAP_CACHE = {}


def _read(rel):
    if rel not in _MAP_CACHE:
        with open(os.path.join(ROOT, rel), encoding='utf-8') as f:
            _MAP_CACHE[rel] = f.read()
    return _MAP_CACHE[rel]


def map_link_problems(url):
    """The map link must open something that exists: a Word Map word, a Han Map
    character, or an article id. A typo silently opens the map's default."""
    from urllib.parse import unquote
    m = re.match(re.escape(SITE) + r'/(\w+)\.html(?:#(.*))?$', url)
    if not m:
        return [f'map_url {url} is not a langmaps.com/<map>.html link']
    page, frag = m.group(1), unquote(m.group(2) or '')
    if page not in ('wordmap', 'hanmap', 'namemap', 'timemap', 'index', 'tree'):
        return [f'map_url points at unknown page {page}.html']
    params = dict(kv.split('=', 1) for kv in frag.split('&') if '=' in kv)
    out = []
    if 'w' in params:
        w = params['w']
        if page == 'wordmap' and not os.path.isfile(os.path.join(ROOT, 'words', w + '.js')):
            out.append(f'Word Map has no word "{w}" (no words/{w}.js)')
        if page == 'hanmap':
            han = re.search(r'const HAN_LIST = (\[.*?\]);', _read('hanmap_data.js')).group(1)
            if f'"{w}"' not in han and f'"{w}:1"' not in han:
                out.append(f'Han Map has no character "{w}"')
    if 'trivia' in params and params['trivia'] != 'index':
        src = {'wordmap': 'wordmap_trivia.js', 'hanmap': 'hanmap_trivia.js',
               'namemap': 'namemap_trivia.js', 'timemap': 'timemap_trivia.js'}.get(page)
        tid = params['trivia']
        pat = '["\']?id["\']?\\s*:\\s*["\']' + re.escape(tid) + '["\']'
        if not src or not re.search(pat, _read(src)):
            out.append(f'{page} has no article "{tid}"')
    return out


def lint(posts):
    out = []
    slugs = {}
    for p in posts:
        path = p['_path']
        # a draft is not published, so its problems are reported but block nothing
        lvl = 'warn' if p.get('draft') else 'error'
        err = lambda m, lvl=lvl, path=path: out.append((lvl, path, m))
        warn = lambda m, path=path: out.append(('warn', path, m))
        for k in REQUIRED:
            if not p.get(k):
                err(f'missing front-matter field "{k}"')
        for k in p:
            if not k.startswith('_') and k not in ALLOWED:
                err(f'unknown front-matter field "{k}"')
        if p.get('slug'):
            if not re.fullmatch(r'[a-z0-9]+(-[a-z0-9]+)*', p['slug']):
                err('slug must be lowercase ascii words joined by hyphens')
            if p['slug'] in slugs:
                err(f'slug "{p["slug"]}" also used by {slugs[p["slug"]]}')
            slugs[p['slug']] = p['_folder']
            if not p['_folder'].endswith('_' + p['slug']):
                err(f'folder name must be <date>_{p["slug"]}')
        if p.get('date'):
            if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', str(p['date'])):
                err('date must be YYYY-MM-DD')
            elif not p['_folder'].startswith(str(p['date']) + '_'):
                err('folder must start with the date')
        lead = p.get('lead') or []
        if lead and isinstance(lead, list) and not all(isinstance(x, str) for x in lead):
            err('every lead item must be a plain string (quote it if it contains ": ")')
            p['lead'] = [str(x) for x in lead]
        if lead and not (isinstance(lead, list) and len(lead) == 3):
            err('lead must be a list of exactly 3 bullet sentences')
        if p.get('hero') and not os.path.isfile(os.path.join(p['_dir'], p['hero'])):
            err(f'hero image {p["hero"]} not found')
        if p.get('map_url') and not str(p['map_url']).startswith(SITE + '/'):
            err('map_url must start with https://langmaps.com/')
        if p.get('map_url') and re.search(r'wordmap\.html\?w=', str(p['map_url'])):
            err('Word Map links use #w=, not ?w=')
        if p.get('map_url'):
            for problem in map_link_problems(str(p['map_url'])):
                err(problem)
        if p.get('tags') and not all(re.fullmatch(r'[a-z0-9-]+', t) for t in p['tags']):
            err('tags are lowercase-hyphenated (see GUIDE.md tag list)')
        if p.get('series') and not p.get('part'):
            err('series posts need part:')
        body = p['_body']
        h2 = re.findall(r'(?m)^##\s+\S', body)
        if len(h2) < 3:
            err(f'body has {len(h2)} "##" sections; at least 3 are required')
        words = len(re.findall(r"[A-Za-z]+(?:'[a-z]+)?", plain(body)))
        if words < 350:
            err(f'body is {words} English words; the minimum is 350')
        for pat, msg in FB_ARTIFACTS:
            if re.search(pat, body, re.M):
                err(msg)
        if re.search(r'(?m)^>\s*$\n\s*\n', body):
            err('empty ">" line followed by a blank line (Facebook quote-export artifact)')
        for m in re.finditer(r'!\[[^\]]*\]\(([^)\s]+)', body):
            if not m.group(1).startswith('http') and not os.path.isfile(os.path.join(p['_dir'], m.group(1))):
                err(f'image {m.group(1)} not found')
        for m in re.finditer(r'!\[\]\(', body):
            err('image without alt text')
        if '“' in body or '”' in body:
            warn('curly double quotes; the corpus uses straight "…"')
        for f in os.listdir(p['_dir']):
            full = os.path.join(p['_dir'], f)
            if f.lower().endswith(('.jpg', '.jpeg', '.png', '.webp')) and Image is not None:
                with Image.open(full) as im:
                    if max(im.size) > IMG_MAX:
                        err(f'{f} is {im.size[0]}×{im.size[1]}; run `import` or resize to ≤{IMG_MAX}px')
                if os.path.getsize(full) > 600_000:
                    warn(f'{f} is {os.path.getsize(full)//1024} KB')
    return out


def cmd_check():
    problems = lint(load_posts(include_drafts=True))
    for lvl, path, msg in problems:
        print(f'  {lvl.upper():5} {os.path.relpath(path, ROOT)}: {msg}')
    errors = sum(1 for p in problems if p[0] == 'error')
    stale = []
    if not errors:
        posts, files = render_all()
        for rel, content in files.items():
            full = os.path.join(ROOT, rel)
            if not os.path.isfile(full) or open(full, encoding='utf-8').read() != content:
                stale.append(rel)
        for p in posts:
            if not os.path.isfile(os.path.join(THUMBS, thumb_name(p))):
                stale.append(f'sinosphere/thumbs/{thumb_name(p)}')
        for s in stale:
            print(f'  STALE {s} — run: python3 tools/build_sinosphere.py build')
    total = errors + len(stale)
    print(f'sinosphere problems: {total}')
    return 1 if total else 0


