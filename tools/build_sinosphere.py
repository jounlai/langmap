def inline(s):
    """Inline markdown -> HTML. Escapes first, then applies the few constructs we allow."""
    out = []
    # links and images are pulled out before escaping so their URLs survive intact
    parts = re.split(r'(!?\[[^\]]*\]\([^)\s]+(?:\s+"[^"]*")?\))', s)
    for part in parts:
        m = re.fullmatch(r'(!?)\[([^\]]*)\]\(([^)\s]+)(?:\s+"([^"]*)")?\)', part)
        if m and not m.group(1):
            label, url = m.group(2), m.group(3)
            ext = url.startswith('http') and not url.startswith(SITE)
            attrs = ' target="_blank" rel="noopener"' if ext else ''
            out.append(f'<a href="{html.escape(url, quote=True)}"{attrs}>{inline_marks(label)}</a>')
        else:
            out.append(inline_marks(part))
    return ''.join(out)


def inline_marks(s):
    # \* is a literal asterisk (reconstructed forms: \*mit); park it so the
    # emphasis rules below do not see it
    s = s.replace('\\*', '\x00')
    s = html.escape(s, quote=False)
    s = re.sub(r'`([^`]+)`', r'<code>\1</code>', s)
    s = re.sub(r'\*\*\*(.+?)\*\*\*', r'<strong><em>\1</em></strong>', s)
    s = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', s)
    s = re.sub(r'(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])', r'<em>\1</em>', s)
    s = re.sub(r'(https?://[^\s<]+[^\s<.,;:)])', r'<a href="\1" target="_blank" rel="noopener">\1</a>', s)
    return s.replace('\x00', '*')


def lines_to_html(lines):
    return '<br>'.join(inline(l.strip()) for l in lines)


def render_body(body, post, img_url):
    """Block-level parse. Returns (html, toc[(id, text)])."""
    lines = body.split('\n')
    out, toc = [], []
    i = 0
    used_ids = set()

    def heading_id(text):
        base = slugify(re.sub(r'[*`]', '', text)) or 'section'
        hid, n = base, 2
        while hid in used_ids:
            hid, n = f'{base}-{n}', n + 1
        used_ids.add(hid)
        return hid

    while i < len(lines):
        line = lines[i]
        st = line.strip()
        if not st:
            i += 1
            continue
        m = re.match(r'^(#{2,3})\s+(.*)$', st)
        if m:
            level, text = len(m.group(1)), m.group(2).strip()
            hid = heading_id(text)
            if level == 2:
                toc.append((hid, re.sub(r'[*`]', '', text)))
            out.append(f'<h{level} id="{hid}">{inline(text)}</h{level}>')
            i += 1
            continue
        m = re.match(r'^!\[([^\]]*)\]\(([^)\s]+)(?:\s+"([^"]*)")?\)$', st)
        if m:
            alt, src, cap = m.group(1), m.group(2), m.group(3)
            src_url = img_url(src)
            fig = f'<figure><img src="{html.escape(src_url)}" alt="{html.escape(alt)}" loading="lazy" decoding="async">'
            if cap:
                fig += f'<figcaption>{inline(cap)}</figcaption>'
            out.append(fig + '</figure>')
            i += 1
            continue
        if st.startswith('>'):
            block = []
            while i < len(lines) and lines[i].strip().startswith('>'):
                block.append(re.sub(r'^>\s?', '', lines[i].strip()))
                i += 1
            # paragraphs inside the quote are separated by a bare ">" line
            paras, cur = [], []
            for b in block:
                if b.strip():
                    cur.append(b)
                elif cur:
                    paras.append(cur)
                    cur = []
            if cur:
                paras.append(cur)
            inner = ''.join(f'<p>{lines_to_html(p)}</p>' for p in paras)
            out.append(f'<div class="example">{inner}</div>')
            continue
        if st.startswith('|'):
            rows = []
            while i < len(lines) and lines[i].strip().startswith('|'):
                rows.append(lines[i].strip())
                i += 1
            cells = [[c.strip() for c in r.strip('|').split('|')] for r in rows]
            has_head = len(cells) > 1 and all(re.fullmatch(r':?-{2,}:?', c) for c in cells[1])
            h = '<div class="table-wrap"><table>'
            if has_head:
                h += '<thead><tr>' + ''.join(f'<th>{inline(c)}</th>' for c in cells[0]) + '</tr></thead>'
                cells = cells[2:]
            h += '<tbody>' + ''.join('<tr>' + ''.join(f'<td>{inline(c)}</td>' for c in r) + '</tr>' for r in cells)
            out.append(h + '</tbody></table></div>')
            continue
        if re.match(r'^[*-]\s+', st) or re.match(r'^\d+\.\s+', st):
            ordered = bool(re.match(r'^\d+\.\s+', st))
            pat = r'^\d+\.\s+' if ordered else r'^[*-]\s+'
            items = []
            while i < len(lines) and re.match(pat, lines[i].strip()):
                items.append(re.sub(pat, '', lines[i].strip()))
                i += 1
                # a continuation line (indented, not a new item) joins the item
                while i < len(lines) and lines[i].startswith('  ') and lines[i].strip() \
                        and not re.match(pat, lines[i].strip()):
                    items[-1] += ' ' + lines[i].strip()
                    i += 1
            tag = 'ol' if ordered else 'ul'
            out.append(f'<{tag}>' + ''.join(f'<li>{inline(t)}</li>' for t in items) + f'</{tag}>')
            continue
        # paragraph: consecutive non-blank lines; single newlines are line breaks
        para = []
        while i < len(lines) and lines[i].strip() and not re.match(r'^(#{2,3}\s|>|\||[*-]\s|\d+\.\s|!\[)', lines[i].strip()):
            para.append(lines[i])
            i += 1
        if not para:  # a line that looked like a block start but did not parse
            para.append(lines[i])
            i += 1
        cls = ''
        if len(para) == 1 and re.fullmatch(r'\*\*[^*].*\*\*', para[0].strip()):
            cls = ' class="punch"'
        out.append(f'<p{cls}>{lines_to_html(para)}</p>')
    return '\n'.join(out), toc


def plain(s):
    s = re.sub(r'!\[[^\]]*\]\([^)]*\)', '', s)
    s = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', s)
    return re.sub(r'[*`_>#]', '', s.replace('\\*', '\x00')).replace('\x00', '*').strip()


