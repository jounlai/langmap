def thumb_name(post):
    return f'{post["slug"]}.jpg'


def make_thumb(post):
    if Image is None:
        raise SystemExit('Pillow is needed for thumbnails: pip install pillow')
    os.makedirs(THUMBS, exist_ok=True)
    src = os.path.join(post['_dir'], post['hero'])
    dst = os.path.join(THUMBS, thumb_name(post))
    if os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src):
        return
    im = Image.open(src).convert('RGB')
    w, h = im.size
    if w > THUMB_W:
        im = im.resize((THUMB_W, round(h * THUMB_W / w)), Image.LANCZOS)
    im.save(dst, 'JPEG', quality=80, optimize=True, progressive=True)


def part_title(p):
    """'Series Title. Part 3: Subtitle' -> 'Subtitle' for the series nav."""
    t = p['title']
    if p.get('series') and t.startswith(p['series']):
        t = t[len(p['series']):]
    t = re.sub(r'^[\s.:,—–-]*(\(?Part\s+\d+\)?[\s.:,—–-]*)?', '', t)
    return t or p['title']


def article_page(post, prev_post, next_post, series_posts):
    folder = post['_folder']

    def img_url(src):
        return src if src.startswith('http') else f'posts/{folder}/{src}'

    body_html, toc = render_body(post['_body'], post, img_url)
    url = f'{BASE}{post["slug"]}.html'
    desc = post.get('description') or plain(post['lead'][0])
    hero_abs = BASE + img_url(post['hero'])
    title = post['title']

    ld = {
        '@context': 'https://schema.org', '@type': 'Article', 'headline': title,
        'datePublished': post['date'], 'dateModified': post.get('revised') or post['date'],
        'image': hero_abs, 'inLanguage': 'en', 'mainEntityOfPage': url,
        'author': {'@type': 'Person', 'name': 'Jounlai Cho'},
        'publisher': {'@type': 'Organization', 'name': 'Heuron Inc.', 'url': 'https://heuron.com'},
    }
    import json
    extra = f'<script type="application/ld+json">{json.dumps(ld, ensure_ascii=False)}</script>\n'

    lead = ''.join(f'<li>{inline(x)}</li>' for x in post['lead'])
    meta_bits = [f'<time datetime="{post["date"]}">{fmt_date(post["date"])}</time>']
    if post.get('revised') and post['revised'] != post['date']:
        meta_bits.append(f'revised <time datetime="{post["revised"]}">{fmt_date(post["revised"])}</time>')
    tags = ''.join(f'<a class="tag" href="./#tag={html.escape(t)}">{html.escape(t)}</a>' for t in post['tags'])

    series_html = ''
    if series_posts:
        items = []
        for sp in series_posts:
            label = f'Part {sp.get("part")}: {html.escape(part_title(sp))}'
            if sp is post:
                items.append(f'<li aria-current="page"><strong>{label}</strong></li>')
            else:
                items.append(f'<li><a href="{sp["slug"]}.html">{label}</a></li>')
        series_html = (f'<nav class="series" aria-label="Series"><p class="series-name">Series · '
                       f'{html.escape(post["series"])}</p><ol>{"".join(items)}</ol></nav>')

    toc_html = ''
    if len(toc) >= 4:
        toc_html = ('<details class="toc"><summary>Contents</summary><ol>' +
                    ''.join(f'<li><a href="#{i}">{html.escape(t)}</a></li>' for i, t in toc) +
                    '</ol></details>')

    sources_html = ''
    if post.get('sources'):
        sources_html = ('<section class="sources"><h2 id="sources">Sources</h2><ul>' +
                        ''.join(f'<li>{inline(s)}</li>' for s in post['sources']) + '</ul></section>')

    pn = []
    if next_post:   # newer
        pn.append(f'<a class="newer" href="{next_post["slug"]}.html"><span>Newer</span>{html.escape(next_post["title"])}</a>')
    if prev_post:   # older
        pn.append(f'<a class="older" href="{prev_post["slug"]}.html"><span>Older</span>{html.escape(prev_post["title"])}</a>')

    fb = ''
    if post.get('fb'):
        fb = f' · <a href="{html.escape(post["fb"])}" target="_blank" rel="noopener">Facebook post</a>'

    return head(f'{title} — LangMap Sinosphere', desc, url, hero_abs, extra=extra) + f'''<body>
{header()}<main class="article">
<article>
  <p class="kicker"><a href="./">{CORNER_NAME}</a> · {' · '.join(meta_bits)}{fb}</p>
  <h1>{inline(title)}</h1>
  <ul class="lead">{lead}</ul>
  <figure class="hero"><img src="{html.escape(img_url(post['hero']))}" alt="{html.escape(post['hero_alt'])}" decoding="async"></figure>
  {series_html}{toc_html}
  <div class="body">
{body_html}
  </div>
  <aside class="maplink"><a href="{html.escape(post['map_url'])}"><span class="maplink-k">Explore on LangMap</span><span class="maplink-t">{inline(post['map_label'])}</span><span class="maplink-arrow" aria-hidden="true">→</span></a></aside>
  {sources_html}
  <p class="tags">{tags}</p>
</article>
<nav class="pn" aria-label="More articles">{''.join(pn)}</nav>
<p class="back"><a href="./">← All Sinosphere articles</a></p>
</main>
{footer()}</body>
</html>
'''


def index_page(posts):
    all_tags = {}
    for p in posts:
        for t in p['tags']:
            all_tags[t] = all_tags.get(t, 0) + 1
    chips = '<button type="button" class="chip on" data-tag="">All</button>' + ''.join(
        f'<button type="button" class="chip" data-tag="{html.escape(t)}">{html.escape(t)} <small>{n}</small></button>'
        for t, n in sorted(all_tags.items(), key=lambda kv: (-kv[1], kv[0])))
    cards = []
    for p in posts:
        lead = html.escape(plain(p['lead'][0]))
        part = f'<span class="part">Part {p["part"]}</span> ' if p.get('part') else ''
        cards.append(
            f'<li class="card" data-tags="{html.escape(" ".join(p["tags"]))}">'
            f'<a href="{p["slug"]}.html"><img src="thumbs/{thumb_name(p)}" alt="" loading="lazy" decoding="async" width="640">'
            f'<div class="card-text"><time datetime="{p["date"]}">{fmt_date(p["date"])}</time>'
            f'<h2>{part}{inline_marks(p["title"])}</h2><p>{lead}</p></div></a></li>')
    newest = posts[0]
    og = BASE + 'thumbs/' + thumb_name(newest)
    script = '''<script>
(function () {
  var chips = document.querySelectorAll('.chip'), cards = document.querySelectorAll('.card');
  function apply(tag) {
    chips.forEach(function (c) { c.classList.toggle('on', c.getAttribute('data-tag') === tag); });
    cards.forEach(function (c) {
      c.hidden = !!tag && (' ' + c.getAttribute('data-tags') + ' ').indexOf(' ' + tag + ' ') < 0;
    });
  }
  chips.forEach(function (c) {
    c.addEventListener('click', function () {
      var t = c.getAttribute('data-tag');
      history.replaceState(null, '', t ? '#tag=' + encodeURIComponent(t) : location.pathname);
      apply(t);
    });
  });
  var m = /tag=([^&]+)/.exec(location.hash);
  if (m) apply(decodeURIComponent(m[1]));
})();
</script>
'''
    return head(f'{CORNER_NAME} — LangMap', CORNER_DESC, BASE, og, og_type='website') + f'''<body>
{header()}<main class="index">
<section class="intro">
  <h1><span class="seal big">漢</span>{CORNER_NAME}</h1>
  <p class="sub">{CORNER_SUB}</p>
  <p>{CORNER_DESC} {len(posts)} article{"s" if len(posts) != 1 else ""} so far. Each one ends with a link to the map where you can compare the forms yourself.</p>
</section>
<div class="chips" role="toolbar" aria-label="Filter by topic">{chips}</div>
<ol class="cards" reversed>
{chr(10).join(cards)}
</ol>
</main>
{footer()}{script}</body>
</html>
'''


def feed(posts):
    now = dt.datetime.now(dt.timezone.utc).strftime('%a, %d %b %Y %H:%M:%S +0000')
    items = []
    for p in posts[:30]:
        d = dt.datetime.strptime(p['date'], '%Y-%m-%d').strftime('%a, %d %b %Y 00:00:00 +0000')
        items.append(f'''<item><title>{html.escape(p["title"])}</title><link>{BASE}{p["slug"]}.html</link>
<guid>{BASE}{p["slug"]}.html</guid><pubDate>{d}</pubDate><description>{html.escape(" ".join(plain(x) for x in p["lead"]))}</description></item>''')
    del now
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0"><channel>
<title>LangMap Sinosphere</title><link>{BASE}</link><description>{html.escape(CORNER_DESC)}</description><language>en</language>
{chr(10).join(items)}
</channel></rss>
'''


def sitemap_block(posts):
    rows = [f'    <url>\n        <loc>{BASE}</loc>\n        <lastmod>{posts[0]["date"]}</lastmod>\n'
            f'        <changefreq>weekly</changefreq>\n        <priority>0.7</priority>\n    </url>']
    for p in posts:
        rows.append(f'    <url>\n        <loc>{BASE}{p["slug"]}.html</loc>\n        <lastmod>{p.get("revised") or p["date"]}</lastmod>\n'
                    f'        <priority>0.6</priority>\n    </url>')
    return '    ' + SITEMAP_START + '\n' + '\n'.join(rows) + '\n    ' + SITEMAP_END


def apply_sitemap(text, block):
    if SITEMAP_START in text:
        a = text.index('    ' + SITEMAP_START) if ('    ' + SITEMAP_START) in text else text.index(SITEMAP_START)
        b = text.index(SITEMAP_END) + len(SITEMAP_END)
        return text[:a] + block + text[b:]
    return text.replace('</urlset>', block + '\n</urlset>')


def series_parts(posts):
    groups = {}
    for p in posts:
        if p.get('series'):
            groups.setdefault(p['series'], []).append(p)
    for g in groups.values():
        g.sort(key=lambda p: p.get('part') or 0)
    return groups


def render_all():
    """Return {relative_path: content} for every generated text file."""
    posts = load_posts()
    if not posts:
        raise SystemExit('no posts')
    groups = series_parts(posts)
    files = {}
    for i, p in enumerate(posts):
        newer = posts[i - 1] if i > 0 else None
        older = posts[i + 1] if i + 1 < len(posts) else None
        files[f'sinosphere/{p["slug"]}.html'] = article_page(p, older, newer, groups.get(p.get('series')))
    files['sinosphere/index.html'] = index_page(posts)
    files['sinosphere/feed.xml'] = feed(posts)
    with open(os.path.join(ROOT, 'sitemap.xml'), encoding='utf-8') as f:
        files['sitemap.xml'] = apply_sitemap(f.read(), sitemap_block(posts))
    return posts, files


def cmd_build():
    problems = lint(load_posts(include_drafts=True))
    errors = [p for p in problems if p[0] == 'error']
    for lvl, path, msg in problems:
        print(f'  {lvl.upper():5} {os.path.relpath(path, ROOT)}: {msg}')
    if errors:
        raise SystemExit(f'{len(errors)} error(s); nothing written')
    posts, files = render_all()
    expected = {os.path.join(ROOT, k) for k in files}
    for old in os.listdir(CORNER):
        full = os.path.join(CORNER, old)
        if old.endswith('.html') and full not in expected:
            os.remove(full)
            print(f'  removed stale {old}')
    for rel, content in files.items():
        with open(os.path.join(ROOT, rel), 'w', encoding='utf-8') as f:
            f.write(content)
    keep = {thumb_name(p) for p in posts}
    for p in posts:
        make_thumb(p)
    if os.path.isdir(THUMBS):
        for t in os.listdir(THUMBS):
            if t not in keep:
                os.remove(os.path.join(THUMBS, t))
    print(f'built {len(posts)} articles → sinosphere/')


