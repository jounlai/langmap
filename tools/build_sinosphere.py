def slugify(s):
    import unicodedata
    s = unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode().lower()
    s = re.sub(r"[’'`]", '', s)
    s = re.sub(r'[^a-z0-9]+', '-', s)
    return s.strip('-')[:60].strip('-')


def split_front_matter(text, path):
    if not text.startswith('---\n'):
        raise ValueError(f'{path}: no front matter (file must start with ---)')
    end = text.find('\n---\n', 4)
    if end < 0:
        raise ValueError(f'{path}: front matter is not closed with ---')
    meta = yaml.safe_load(text[4:end]) or {}
    body = text[end + 5:]
    return meta, body


def load_posts(include_drafts=False):
    posts = []
    if not os.path.isdir(POSTS):
        return posts
    for name in sorted(os.listdir(POSTS)):
        d = os.path.join(POSTS, name)
        p = os.path.join(d, 'post.md')
        if not os.path.isfile(p):
            continue
        with open(p, encoding='utf-8') as f:
            text = f.read().replace('\r\n', '\n')
        meta, body = split_front_matter(text, p)
        meta['_dir'] = d
        meta['_folder'] = name
        meta['_body'] = body
        meta['_path'] = p
        if isinstance(meta.get('date'), (dt.date, dt.datetime)):
            meta['date'] = meta['date'].strftime('%Y-%m-%d')
        if isinstance(meta.get('revised'), (dt.date, dt.datetime)):
            meta['revised'] = meta['revised'].strftime('%Y-%m-%d')
        if meta.get('draft') and not include_drafts:
            continue
        posts.append(meta)
    posts.sort(key=lambda m: (str(m.get('date')), m.get('part') or 0), reverse=True)
    return posts


