def read_fb_index(src):
    """index.md of the FB export: | date | time | folder | images | url |"""
    urls = {}
    p = os.path.join(src, 'index.md')
    if os.path.isfile(p):
        for line in open(p, encoding='utf-8'):
            cols = [c.strip() for c in line.strip().strip('|').split('|')]
            if len(cols) >= 5 and cols[4].startswith('http'):
                urls[cols[2]] = cols[4]
    return urls


def optimise_image(src, dst):
    im = Image.open(src)
    im = im.convert('RGB')
    w, h = im.size
    if max(w, h) > IMG_MAX:
        r = IMG_MAX / max(w, h)
        im = im.resize((round(w * r), round(h * r)), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'JPEG', quality=IMG_QUALITY, optimize=True, progressive=True)
    if os.path.splitext(src)[1].lower() in ('.jpg', '.jpeg') and buf.tell() >= os.path.getsize(src) \
            and max(w, h) <= IMG_MAX:
        shutil.copyfile(src, dst)
    else:
        with open(dst, 'wb') as f:
            f.write(buf.getvalue())


def cmd_import(src):
    if Image is None:
        raise SystemExit('Pillow is needed: pip install pillow')
    urls = read_fb_index(src)
    known_fb = {p.get('fb') for p in load_posts(include_drafts=True)}
    os.makedirs(POSTS, exist_ok=True)
    added = 0
    for name in sorted(os.listdir(src)):
        d = os.path.join(src, name)
        md = os.path.join(d, 'post.md')
        if not os.path.isfile(md):
            continue
        fb = urls.get(name)
        if fb and fb in known_fb:
            continue
        date = name[:10]
        text = open(md, encoding='utf-8').read().replace('\r\n', '\n').strip()
        m = re.match(r'#\s+(.+)', text)
        title = (m.group(1) if m else text.split('\n')[0]).strip().strip('*')
        slug = slugify(title) or slugify(name[11:])
        folder = f'{date}_{slug}'
        dst = os.path.join(POSTS, folder)
        if os.path.exists(dst):
            print(f'  skip {name}: {folder} exists')
            continue
        os.makedirs(dst)
        imgs = sorted(f for f in os.listdir(d) if f.lower().endswith(('.jpg', '.jpeg', '.png', '.webp')))
        for f in imgs:
            optimise_image(os.path.join(d, f), os.path.join(dst, os.path.splitext(f)[0] + '.jpg'))
        lead = re.findall(r'(?m)^\*\s+(.+)$', text)[:3]
        fm = {
            'title': title, 'slug': slug, 'date': date, 'draft': True,
            'fb': fb or '', 'tags': [], 'hero': 'image1.jpg' if imgs else '',
            'hero_alt': '', 'map_label': '', 'map_url': '', 'lead': lead or ['', '', ''],
        }
        with open(os.path.join(dst, 'post.md'), 'w', encoding='utf-8') as f:
            f.write('---\n' + yaml.safe_dump(fm, allow_unicode=True, sort_keys=False, width=1000) + '---\n\n'
                    '<!-- ORIGINAL FACEBOOK TEXT BELOW: rewrite it to GUIDE.md §3, then delete this line and draft: true -->\n\n'
                    + text + '\n')
        print(f'  + {folder} ({len(imgs)} image(s))')
        added += 1
    print(f'imported {added} new post(s) as drafts into sinosphere/posts/')


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'build'
    if cmd == 'build':
        cmd_build()
    elif cmd == 'check':
        sys.exit(cmd_check())
    elif cmd == 'import' and len(sys.argv) > 2:
        cmd_import(sys.argv[2])
    else:
        print(__doc__)
        sys.exit(2)
