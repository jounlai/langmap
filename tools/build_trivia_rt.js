#!/usr/bin/env node
/*
 * build_trivia_rt.js — the runtime copy of the Name Map and Time Map trivia,
 * read by trivia_reader.js. Same split as build_hanmap_trivia_rt.js:
 *
 *   <map>_trivia.js            source: every article, all 19 UI languages inline
 *                              (what the trivia guards and the SEO export read)
 *   <map>_trivia_rt/base.js    every article, titles and summaries in all
 *                              languages, bodies in English only
 *   <map>_trivia_rt/<ui>.js    the bodies in one other language
 *
 * base.js carries a hash of everything generated (LMT_BUILD[map]); the
 * language files are requested with it as their ?v=.
 *
 *   node tools/build_trivia_rt.js           # write
 *   node tools/build_trivia_rt.js --check   # print "stale: N" (check_all)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const MAPS = ['namemap', 'timemap'];
// build_br.js owns these pre-compressed siblings.
const BR_OWNED = new Set(['base.js.br']);

function load(map) {
    const ctx = vm.createContext({});
    vm.runInContext('var window = this;', ctx);
    vm.runInContext(fs.readFileSync(path.join(ROOT, map + '_trivia.js'), 'utf8'), ctx, { filename: map + '_trivia.js' });
    return JSON.parse(JSON.stringify(vm.runInContext('window.TRIVIA_ARTICLES', ctx) || []));
}

function build(map) {
    const arts = load(map);
    const per = {};
    for (const a of arts) {
        const body = a.body || {};
        for (const ui of Object.keys(body)) if (ui !== 'en') (per[ui] = per[ui] || {})[a.id] = body[ui];
        a.body = { en: body.en || '' };
    }
    const head = '// GENERATED by tools/build_trivia_rt.js from ' + map + '_trivia.js — do not edit.\n';
    const files = {};
    for (const ui of Object.keys(per).sort()) {
        files[ui + '.js'] = head + '((window.LMT_BODY = window.LMT_BODY || {})[' + JSON.stringify(map) + '] = window.LMT_BODY[' +
            JSON.stringify(map) + '] || {})[' + JSON.stringify(ui) + '] = ' + JSON.stringify(per[ui]) + ';\n';
    }
    const h = crypto.createHash('sha1').update(JSON.stringify(arts));
    for (const f of Object.keys(files)) h.update(f).update(files[f]);
    const hash = h.digest('hex').slice(0, 12);
    const k = JSON.stringify(map);
    files['base.js'] = head
        + '(window.LMT_BUILD = window.LMT_BUILD || {})[' + k + '] = ' + JSON.stringify(hash) + ';\n'
        + '(window.LMT_LANGS = window.LMT_LANGS || {})[' + k + '] = ' + JSON.stringify(Object.keys(per).sort()) + ';\n'
        + '(window.LMT_ARTICLES = window.LMT_ARTICLES || {})[' + k + '] = ' + JSON.stringify(arts) + ';\n';
    return files;
}

const CHECK = process.argv.includes('--check');
let stale = 0;
for (const map of MAPS) {
    const out = path.join(ROOT, map + '_trivia_rt');
    const files = build(map);
    if (CHECK) {
        const bad = Object.entries(files).filter(([f, s]) => !fs.existsSync(path.join(out, f)) || fs.readFileSync(path.join(out, f), 'utf8') !== s).map(([f]) => f);
        const extra = fs.existsSync(out) ? fs.readdirSync(out).filter((f) => !(f in files) && !BR_OWNED.has(f)) : [];
        if (bad.length || extra.length) {
            console.log(map + '_trivia_rt/ is stale: ' + bad.concat(extra.map((f) => f + ' (orphan)')).join(', '));
            console.log('fix: node tools/build_trivia_rt.js && node tools/page_asset_version_check.js --bump && node tools/build_br.js');
        }
        stale += bad.length + extra.length;
    } else {
        fs.mkdirSync(out, { recursive: true });
        for (const f of fs.readdirSync(out)) if (!(f in files) && !BR_OWNED.has(f)) fs.unlinkSync(path.join(out, f));
        for (const [f, s] of Object.entries(files)) fs.writeFileSync(path.join(out, f), s);
        console.log('wrote ' + Object.keys(files).length + ' files to ' + map + '_trivia_rt/');
    }
}
if (CHECK) console.log('stale: ' + stale);
