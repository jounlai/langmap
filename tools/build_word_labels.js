#!/usr/bin/env node
/*
 * build_word_labels.js — extract the label/definition blocks of words/*.js
 * into a single small file, word_labels.js.
 *
 * Why: wordmap.html used to load all 25 words/<id>.js up front (≈344 KB
 * gzipped) even though the map shows one word at a time. The bulk of each file
 * is `data` — 1,113 language cells. The `label` and `definition` blocks are
 * what the UI needs immediately (the word <select>, the definition line), and
 * all 25 of them together are ≈30 KB gzipped.
 *
 * So: ship word_labels.js eagerly, and fetch words/<id>.js on demand.
 *
 * Run: node tools/build_word_labels.js            (writes word_labels.js)
 *      node tools/build_word_labels.js --check    (exit 1 if stale)
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'word_labels.js');

global.window = {};
global.WORDS = {};
for (const f of fs.readdirSync(path.join(ROOT, 'words')).filter(f => f.endsWith('.js'))) {
    // eslint-disable-next-line no-eval
    eval(fs.readFileSync(path.join(ROOT, 'words', f), 'utf8'));
}

// word_manifest.js owns display order; mirror it so the select is stable.
// It declares `const WORD_ORDER`, which an eval keeps in its own scope, so
// pull the value out explicitly rather than reaching for a global.
// eslint-disable-next-line no-eval
const WORD_ORDER = eval(fs.readFileSync(path.join(ROOT, 'word_manifest.js'), 'utf8') + ';WORD_ORDER');

const out = {};
for (const id of WORD_ORDER) {
    const w = WORDS[id];
    if (!w) { console.error(`missing words/${id}.js`); process.exit(1); }
    out[id] = { label: w.label || {}, definition: w.definition || {} };
}

const body = `/* word_labels.js — GENERATED by tools/build_word_labels.js. Do not edit.
 *
 * The label + definition blocks of every words/<id>.js, so wordmap.html can
 * build the word selector and its definition line without downloading the
 * 1,113-language \`data\` block of all 25 words. The data arrives per word,
 * on demand. Regenerate whenever a label or definition changes.
 */
window.WORD_LABELS = ${JSON.stringify(out)};
`;

if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== body) {
        console.log('stale: 1');
        console.error('word_labels.js is stale — run: node tools/build_word_labels.js');
        process.exit(0); // exit 0 so check_all can scrape the count
    }
    console.log('stale: 0');
    process.exit(0);
}

fs.writeFileSync(OUT, body);
console.log(`word_labels.js written (${WORD_ORDER.length} words, ${body.length} bytes)`);
